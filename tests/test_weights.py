from __future__ import annotations

from pathlib import Path

import numpy as np
import pytest
import torch

from deepbedmap.assets import WEIGHTS, cached_path
from deepbedmap.model import GeneratorModel, parameter_count
from deepbedmap.weights import (
    convert_legacy_checkpoint,
    inspect_legacy_checkpoint,
    legacy_key_to_torch,
    load_native_checkpoint,
    save_native_checkpoint,
)


def test_legacy_key_mapping() -> None:
    assert legacy_key_to_torch("input_block/conv_on_X/W") == "input_block.conv_on_X.weight"
    assert (
        legacy_key_to_torch("final_conv_layer1/offset_conv/b")
        == "final_conv_layer1.offset_conv.bias"
    )
    assert (
        legacy_key_to_torch("residual_network/11/residual_dense_block1/conv_layer1/W")
        == "residual_network.1.residual_dense_block1.conv_layer1.weight"
    )
    assert (
        legacy_key_to_torch("residual_network/1/residual_dense_block1/conv_layer1/W")
        == "residual_network.11.residual_dense_block1.conv_layer1.weight"
    )
    with pytest.raises(ValueError, match="Unsupported"):
        legacy_key_to_torch("metadata/version")


RELEASE_WEIGHTS = cached_path(WEIGHTS)


@pytest.mark.integration
@pytest.mark.skipif(not RELEASE_WEIGHTS.exists(), reason="public checkpoint is not cached")
def test_public_checkpoint_manifest_and_conversion(tmp_path: Path) -> None:
    info = inspect_legacy_checkpoint(RELEASE_WEIGHTS)
    assert info["arrays"] == 384
    assert info["num_residual_blocks"] == 12
    assert info["parameters"] == 8_907_749
    assert info["all_finite"] is True

    destination = tmp_path / "native.pt"
    convert_legacy_checkpoint(RELEASE_WEIGHTS, destination)
    model, metadata = load_native_checkpoint(destination)
    assert metadata["num_residual_blocks"] == 12
    assert metadata["residual_scaling"] == 0.2
    assert metadata["parameter_count"] == 8_907_749
    assert metadata["weights_release"] == "v1.1.0"
    assert len(metadata["state_sha256"]) == 64
    assert parameter_count(model) == 8_907_749


def test_native_checkpoint_rejects_wrong_architecture(tmp_path: Path) -> None:
    path = save_native_checkpoint(GeneratorModel(num_residual_blocks=1), tmp_path / "wrong.pt")
    with pytest.raises(ValueError, match="metadata does not match"):
        load_native_checkpoint(path)


def test_native_checkpoint_rejects_tampered_state(tmp_path: Path) -> None:
    path = save_native_checkpoint(GeneratorModel(), tmp_path / "tampered.pt")
    payload = torch.load(path, map_location="cpu", weights_only=True)
    first = next(iter(payload["state_dict"].values()))
    first.view(-1)[0] += 1.0
    torch.save(payload, path)
    with pytest.raises(ValueError, match="state digest"):
        load_native_checkpoint(path)


def test_native_checkpoint_rejects_non_finite_state(tmp_path: Path) -> None:
    path = save_native_checkpoint(GeneratorModel(), tmp_path / "non-finite.pt")
    payload = torch.load(path, map_location="cpu", weights_only=True)
    first = next(iter(payload["state_dict"].values()))
    first.view(-1)[0] = torch.nan
    torch.save(payload, path)
    with pytest.raises(ValueError, match="NaN or infinite"):
        load_native_checkpoint(path)


@pytest.mark.integration
@pytest.mark.skipif(not RELEASE_WEIGHTS.exists(), reason="public checkpoint is not cached")
def test_public_checkpoint_matches_chainer_golden_values() -> None:
    """Compare against Chainer 7.0 CPU output generated by the reference tool."""

    from deepbedmap.weights import load_legacy_weights

    def values(shape: tuple[int, ...], modulus: int, scale: float, offset: float) -> np.ndarray:
        data = np.arange(np.prod(shape), dtype=np.float32).reshape(shape)
        return (data % np.float32(modulus)) * np.float32(scale) + np.float32(offset)

    inputs = {
        "x": values((1, 1, 11, 11), 121, 20.0, -2_000.0),
        "w1": values((1, 1, 110, 110), 251, 10.0, 500.0),
        "w2": values((1, 2, 22, 22), 97, 15.0, -720.0),
        "w3": values((1, 1, 11, 11), 31, 0.01, 0.0),
    }
    model = load_legacy_weights(RELEASE_WEIGHTS)
    with torch.inference_mode():
        output = model(**{name: torch.from_numpy(value) for name, value in inputs.items()})
    array = output.numpy()[0, 0]
    expected_points = {
        (0, 0): -1433.738525390625,
        (0, 35): -692.031005859375,
        (35, 0): -270.9671325683594,
        (35, 35): -143.60707092285156,
        (18, 18): -641.6403198242188,
        (7, 11): -521.3176879882812,
        (25, 29): -535.267822265625,
        (3, 17): -404.26678466796875,
        (12, 4): -1040.656494140625,
        (30, 20): -628.630126953125,
        (9, 9): -863.8619995117188,
        (20, 7): -699.289306640625,
        (16, 31): -728.666748046875,
        (27, 2): -480.9366760253906,
        (5, 25): -541.32958984375,
        (33, 14): -192.64495849609375,
    }
    actual_points = np.array([array[index] for index in expected_points], dtype=np.float32)
    np.testing.assert_allclose(
        actual_points,
        np.array(list(expected_points.values()), dtype=np.float32),
        rtol=5e-5,
        atol=0.04,
    )
    np.testing.assert_allclose(
        [array.min(), array.max(), array.mean(), array.std()],
        [-1544.9923095703125, 12.650138854980469, -560.7416381835938, 288.72125244140625],
        rtol=5e-5,
        atol=0.04,
    )
